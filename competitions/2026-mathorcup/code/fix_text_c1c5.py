MAIN = 'latex模板/main.tex'
OK, FAIL = [], []


def rep(path, old, new, tag, count=1):
    s = io.open(path, encoding='utf-8', newline='').read()
    n = s.count(old)
    if n != count:
        FAIL.append((tag, n, count))
        print(f'  ✗ {tag}（{n}/{count}）')
        return
    io.open(path, 'w', encoding='utf-8', newline='').write(s.replace(old, new))
    OK.append(tag)
    print(f'  ✓ {tag}')


