def rep(old, new, tag, count=1):
    global s
    n = s.count(old)
    if n != count:
        FAIL.append((tag, n, count))
        print(f'  ✗ {tag}（{n}/{count}）')
        return
    s = s.replace(old, new)
    OK.append(tag)
    print(f'  ✓ {tag}')


