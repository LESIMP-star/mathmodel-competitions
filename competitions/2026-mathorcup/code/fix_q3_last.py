# -*- coding: utf-8 -*-
"""清掉 Q3 里最后一处旧口径：5 个 Pareto 点 / 280 可行 / 51.3%。"""
import io
import sys

try:
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
except Exception:
    pass

P = 'latex模板/sections/8_问题三.tex'
s = io.open(P, encoding='utf-8', newline='').read()
OK, FAIL = [], []


def rep(old, new, tag):
    global s
    n = s.count(old)
    if n != 1:
        FAIL.append((tag, n))
        print(f'  ✗ {tag}（{n}）')
        return
    s = s.replace(old, new)
    OK.append(tag)
    print(f'  ✓ {tag}')


# ① ε-约束段的「只优化 f1」与「280 次可行」双重过时
rep('多目标按 ε-约束法处理：每次把 $f_2$、$f_3$ 各固定在一个水平上写成约束，只优化 $f_1$，遍历 $(f_2,f_3)$ 的 $20\\times15=300$ 个组合。300 次求解中 280 次可行、20 次因硬约束冲突不可行，280 个可行点全部非支配，筛选后保留 5 个 Pareto 点。',
    '多目标按 ε-约束法处理：把 $f_2$、$f_3$ 各固定在一个水平上写成约束，目标取 $f_1+\\lambda f_3$（$f_1$ 与 $f_3$ 同为代价，$f_2$ 作约束，理由见上），遍历 $(f_2,f_3)$ 的 $20\\times15=300$ 个组合。300 次求解全部可行、全部非支配，按 $f_3$ 分层去重后保留 7 个 Pareto 点。',
    'ε-约束段口径')

# ② 「5 个点」与末尾数字
rep('5 个 Pareto 点全部为 OPTIMAL 状态，$mip\\_gap=0$，两两互不支配，见表~\\ref{tab:q3}。硬约束的超出量取 $t_k-\\tau_k$，负值即低于阈值，在五点上的最小值为 $-0.644$(P4)，即最贴近阈值的那条约束仍留有余量。基线感官偏差为 48.9620，最优解 23.8519，降幅 51.3\\%。',
    '7 个 Pareto 点全部为 OPTIMAL 状态，$mip\\_gap$ 均为 0（P3 为 $3.8\\times10^{-5}$），两两互不支配，见表~\\ref{tab:q3}。硬约束的超出量取 $t_k-\\tau_k$，负值即低于阈值；七个点里只有 P7 的两条硬约束余量同时为 0，即恰好贴住约束，其余各点至少有一条留有余量。基线感官偏差为 48.9620，$f_1$ 最低的 P1 为 20.2063，降幅 58.7\\%。',
    '七点与降幅')

# ③ 图注：8 个化合物 → 10 个
rep('\\caption{最优解改了什么。左图为 8 个化合物的调整幅度，DMS 与松油烯-4-醇下调最重；右图为 $f_1$ 的逐组分解，降幅主要来自酸度、苦度与硫味三类}',
    '\\caption{最优解改了什么。左图为 P1 所改 10 个化合物的调整幅度，松油烯-4-醇、氧化橙花醇与 $\\alpha$-紫罗兰酮均降到检出限；右图为 $f_1$ 的逐组分解}',
    '图注 8→10')

# ④ 迁移对比段：51.3% → 引用 P3（同口径可比）
rep('这个 72.14\\% 明显高于上一节的 51.3\\%，原因是起点不同：上一节从 Tripel 自身中位数出发，本节从 Pils/Lager 的化学谱出发，后者离目标远得多，可改进空间也大。',
    '这个 72.14\\% 高于上一节同一 $f_3$ 档位（P3，7 个化合物）的 51.3\\%，原因是起点不同：上一节从 Tripel 自身中位数出发，本节从 Pils/Lager 的化学谱出发，后者离目标远得多，可改进空间也大。若与上一节的 $f_1$ 最低点 P1 比，迁移的 72.14\\% 则低于 P1 的 58.7\\%——但两者改动的化合物数不同（25 对 10），不宜直接并列。',
    '迁移对比段')

io.open(P, 'w', encoding='utf-8', newline='').write(s)
print(f'\n成功 {len(OK)}，失败 {len(FAIL)}')
for t, n in FAIL:
    print(f'  {t}（{n}）')
